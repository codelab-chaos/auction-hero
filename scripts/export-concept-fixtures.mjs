function lua(v,depth=0){
  if(v==null)return 'nil';
  if(typeof v==='string')return JSON.stringify(v);
  if(typeof v!=='object')return String(v);
  const parts=Array.isArray(v)?v.map(x=>lua(x,depth+1)):Object.entries(v).map(([k,x])=>`[${lua(k,depth+1)}]=${lua(x,depth+1)}`);
  return depth<3?`{\n${'  '.repeat(depth+1)}${parts.join(',\n'+'  '.repeat(depth+1))}\n${'  '.repeat(depth)}}`:`{${parts.join(',')}}`;
}
