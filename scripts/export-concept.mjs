// Read the lab's real modules without modifying them. Checked-in Lua output
// makes WoW independent of the browser/Node runtime. Run from the repo root.
import { createServer } from "../lab/node_modules/vite/dist/node/index.js";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const server = await createServer({configFile:false,root:resolve(root,"lab"),cacheDir:"/tmp/auctionitro-concept-vite",server:{middlewareMode:true},appType:"custom",logLevel:"error"});
function lua(value) {
  if (value == null) return "nil";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) return `{${value.map(lua).join(",")}}`;
  return `{${Object.entries(value).filter(([,v])=>v!==undefined&&typeof v!=="function").map(([k,v])=>`[${lua(k)}]=${lua(v)}`).join(",")}}`;
}
try {
  const modules = await Promise.all(["concept","facets","catalog","signals","price-rules"].map(name=>server.ssrLoadModule(`/src/config/${name}.ts`)));
  const [concept,facets,catalog,signals,pricing] = modules;
  const css=readFileSync(resolve(root,"lab/src/styles.css"),"utf8");
  const palette={};
  for(const block of css.matchAll(/\.cw-window\s*\{([^}]+)\}/g))
    for(const declaration of block[1].matchAll(/--([\w-]+):\s*([^;]+);/g))palette[declaration[1]]=declaration[2].trim();
  function declarations(selector) {
    const escaped=selector.replace(/[.*+?^${}()|[\]\\]/g,"\\$&");
    const blocks=[...css.matchAll(new RegExp(`${escaped}\\s*\\{([^}]+)\\}`,"g"))];
    const merged={};
    for(const block of blocks)for(const d of block[1].matchAll(/([\w-]+):\s*([^;]+);/g))merged[d[1]]=d[2].trim();
    return merged;
  }
  const categories=facets.ITEM_CATEGORIES.map(category=>{
    const refine=category.refine;
    return {...category,refine:refine?{label:refine.label,placement:refine.placement,options:refine.options,
      slotValues:Object.fromEntries(Object.keys(catalog.EQUIP_SLOTS).map(equipLoc=>[equipLoc,refine.read({equipLoc})]).filter(([,v])=>v!==null)),
      preferredSubClasses:refine.pictures?Object.fromEntries(refine.options.map(option=>[option.value,Array.from({length:30},(_,i)=>i).filter(subClassId=>refine.pictures({subClassId},option.value))])):undefined}:undefined};
  });
  const data={window:concept.WINDOW,tabs:concept.CONCEPT_TABS,toggles:concept.BUY_TOGGLES,categories,rail:facets.BUY_RAIL,
    qualities:catalog.QUALITIES,slots:catalog.EQUIP_SLOTS,commodityClasses:[...catalog.COMMODITY_CLASS_IDS],assumptions:catalog.ASSUMPTIONS,
    saleTypes:concept.SALE_TYPES,durations:concept.DURATIONS,defaultDuration:concept.DEFAULT_DURATION,defaultPriceRule:concept.DEFAULT_PRICE_RULE,
    startingBidShare:concept.STARTING_BID_SHARE,priceRules:pricing.PRICE_RULES.map(({id,label,note})=>({id,label,note})),
    confidenceLevels:signals.CONFIDENCE_LEVELS,confidenceRule:signals.CONFIDENCE_RULE,confidencePips:signals.CONFIDENCE_PIPS,
    dealLevels:signals.DEAL_LEVELS,dealRule:signals.DEAL_RULE,dealUnknown:signals.DEAL_UNKNOWN,dealPips:signals.DEAL_PIPS,
    resellMargins:concept.RESELL_MARGINS,resellMinPips:concept.RESELL_MIN_PIPS,buyLimit:concept.BUY_LIST_LIMIT,resellLimit:concept.RESELL_LIST_LIMIT,
    palette,metrics:JSON.parse(readFileSync(resolve(root,"tests/concept-layout.json"),"utf8")).metrics,
    styles:Object.fromEntries([".cw-window .cw-title",".cw-window .cw-tab",".cw-window .cw-tab.active",".cw-window .cw-toggle",".cw-window .cw-toggle.active",".cw-window .cw-action",".cw-buy",".cw-sell",".cw-resell"].map(key=>[key,declarations(key)]))};
  writeFileSync(resolve(root,"AuctioNitro/data/concept.lua"),`-- Generated by scripts/export-concept.mjs from lab/src/config and styles.css.\n-- Do not edit this file; the prototype remains the source.\nlocal _, ns = ...\nns.Concept = ${lua(data)}\n`);
  console.log("Exported lab configuration and effective concept styles to AuctioNitro/data/concept.lua");
} finally { await server.close(); }
