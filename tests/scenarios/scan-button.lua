-- The Scan button waits out the server's limit after a scan.
local ns = Boot()
OpenAuctionHouse()
ShowTab("buy")
local function scanButton()
	return ButtonNamed("Scan") or ButtonNamed("Cancel")
end
local function footerStatus()
	local found = Frames(function(frame)
		return type(frame.text) == "string" and (frame.text:find("^Scanned") or frame.text:find("^No scan"))
	end)
	return found[1] and strip(found[1].text)
end
local function redraw()
	SlashCmdList.AUCTIONHERO("")
	SlashCmdList.AUCTIONHERO("")
	Tick(2)
end

check("ready before any scan", scanButton().disabled, false)
checkMatch("says there is no scan", footerStatus(), "^No scan yet")
Scan()
redraw()
check("held right after a scan", scanButton().disabled, true)
checkMatch("says when the next one is", footerStatus(), "Scanned just now.*Next scan in 15m")
SkipTime(6 * 60)
redraw()
check("still held at 6 minutes", scanButton().disabled, true)
checkMatch("counts down", footerStatus(), "Scanned 6m ago.*Next scan in 9m")
SkipTime(10 * 60)
redraw()
check("ready after 15 minutes", scanButton().disabled, false)
checkMatch("age in minutes", footerStatus(), "^Scanned 16m ago")
SkipTime(119 * 60)
redraw()
checkMatch("age in hours", footerStatus(), "^Scanned 2h 15m ago")
